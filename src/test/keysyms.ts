/** Il carattere di un keysym xkb: '' per i tasti morti, un solo carattere vale se stesso, undefined se il nome non è nella mappa. */
export function keysymChar(name: string): string | undefined {
  if (name.startsWith('dead_')) return ''
  if ([...name].length === 1) return name
  return KEYSYM_CHAR[name]
}
